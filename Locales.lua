local clientLanguage = { deDE = "de" }

--- "auto" follows the game client; a language the addon does not have becomes English.
function ns.ResolveLanguage(preference)
    if preference and locales[preference] then return preference end
    return clientLanguage[GetLocale()] or "en"
end

ns.uiLang = ns.ResolveLanguage("auto")

ns.L = setmetatable({}, {
    __index = function(_, key)
        local active = locales[ns.uiLang]
        return (active and active[key]) or locales.en[key] or key
    end,
})

--- The names in the game's key binding list. Called again after a language change.
function ns.ApplyBindingNames()
    BINDING_NAME_MALDOESSCRIBE_SMART = ns.L.BIND_SMART
    BINDING_NAME_MALDOESSCRIBE_TOOLTIP = ns.L.BIND_TOOLTIP
    BINDING_NAME_MALDOESSCRIBE_CHAT = ns.L.BIND_CHAT
end
ns.ApplyBindingNames()
